//escape sequences
public class ex2 {
    public static void main(String[]args){
        System.out.println(" do \n hardwork ");  //line break karega
        System.out.println("do\thardwork");    //space chordega
        System.out.println("do \bhardwork");   //ek step piche chala gya
        System.out.println("do\'hardwork");     //single quote laga dega eg- do'hardwork
        System.out.println("do\"hardwork");     //double quote insert karta ha eg do"gardwork
        
    }
    
}
